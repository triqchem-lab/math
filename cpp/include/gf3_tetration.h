// 正整数 n 的 Q16 log10 (位长归一化 + 查表, 精度 ≤ 2.5e-3)
[[nodiscard]] inline int64_t q16_log10_u64(uint64_t n) noexcept {
    if (n == 0) return 0;
    int k = 63 - __builtin_clzll(n);          // log2 整数部分
    uint64_t m = (k <= 62) ? (n << (62 - k)) : (n >> (k - 62));  // 归一化 [2^62, 2^63)
    int idx = (int)((m - (1ULL << 62)) >> 50);  // 4096 分桶
    // log10(n) = k·log10(2) + log10(1 + (m−2^62)/2^62)
    return (int64_t)k * 19728 + Q16_LOG10_TABLE[idx];
}

[[nodiscard]] inline int32_t tower_height_from_zhonglv_q16(uint64_t zhonglv_count) noexcept {
    // freq_log10 (Q16) = 2.6355 + zc × 3.4541
    int64_t fl_q16 = 172729 + (int64_t)zhonglv_count * ZHONGLV_LOG10_MULT_Q16;
    // H = log10(freq_log10)/log10(12);  log10(freq_log10_q16) = log10(fl) − log10(2¹⁶)
    int64_t lg = q16_log10_u64((uint64_t)fl_q16) - 315652;   // 315652 = log10(2¹⁶)×2¹⁶
    return (int32_t)((lg * 65536) / 70725);                  // /log10(12) Q16
}

