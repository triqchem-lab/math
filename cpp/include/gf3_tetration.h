// pow10_q16: 10^(x_q16/65536) (x_q16 ≥ 0, 整数+分数拆分)
[[nodiscard]] inline int64_t pow10_q16(int32_t x_q16) noexcept {
    int k = x_q16 >> 16;
    int frac = x_q16 & 0xFFFF;
    int idx = (frac * 4096) >> 16;
    int64_t base = 65536 + Q16_POW10_TABLE[idx];
    int64_t r = base;
    for (int i = 0; i < k && i < 18; ++i) r *= 10;   // 10^k, 域外截断防溢出
    return r;
}

// 12^H 的 Q16 定点计算 (H ≥ 0, 2^(H·log2(12)), 域 [0, ~5] 内精度 ≤ 1e-3 相对)
[[nodiscard]] inline uint64_t zhonglv_from_tower_height(int32_t H_q16) noexcept {
    // 逆映射: fl (值) = 12^H = 10^(H·log10(12));  zc = (fl − 2.6355) / 3.4541
    int64_t log10_fl_q16 = ((int64_t)H_q16 * 70725) >> 16;   // ×log10(12)
    int64_t fl_q16 = pow10_q16((int32_t)log10_fl_q16);
    int64_t zc_q16 = ((fl_q16 - 172729) * 65536) / ZHONGLV_LOG10_MULT_Q16;
    return zc_q16 > 0 ? (uint64_t)(zc_q16 >> 16) : 0;
}

// ═══════════════════════════════════════════════════════
// 三、指数塔层级定义
// ═══════════════════════════════════════════════════════

enum class TowerLevel : uint8_t {
    L0_ROOT     = 0,   // 432 Hz 基频
    L1_TWELVE   = 1,   // 12^12 ≈ 10^13 Hz  (仲吕≈3)
    L2_GROSS    = 2,   // 12^144 ≈ 10^155 Hz (仲吕≈44)
    L3_TETRA    = 3,   // 12^(12^12) ≈ 10^(10^13) Hz (不可达)
};

// 从仲吕闭合判定当前指数塔层级
[[nodiscard]] constexpr TowerLevel classify_level(uint64_t zhonglv_count) noexcept {
    if (zhonglv_count < 4)    return TowerLevel::L0_ROOT;    // <10^16 Hz
    if (zhonglv_count < 45)   return TowerLevel::L1_TWELVE;  // <10^155 Hz
    return TowerLevel::L2_GROSS;  // 10^155+ Hz (当前)
    // TowerLevel::L3_TETRA unreachable with uint64_t
}

// ═══════════════════════════════════════════════════════
// 四、GF(3) 塔层结构
// ═══════════════════════════════════════════════════════

// GF(3) 分解: 每层塔 = 3^k × 4^m 形式
//   L1: 12 = 3^1 × 4^1
//   L2: 144 = 3^2 × 4^2
//   Ln: 12^n = 3^n × 4^n
//
// 仲吕闭合累积: zc 次闭合 → exp_3 = zc×88, exp_2 = -zc×128
//   88 = 11×8 = 仲吕×8级倍增
//   128 = 16×8 = 2^16位宽×8级

/* ── 精确性分层 ──
 * 精确状态: zhonglv_count / exp_3 / exp_2 (整数指数对, 零误差);
 * 派生投影: freq_log10_q16 / tower_height_q16 (Q16 查表, 误差 ≤10 lsb,
 *   仅用于人类可读层级判定与到达估算, 不参与状态演化)。
 */
struct Gf3TowerState {
    uint64_t zhonglv_count;   // 仲吕闭合次数
    int64_t  exp_3;           // 3的指数 (正)
    int64_t  exp_2;           // 2的指数 (负)
    int32_t  freq_log10_q16;  // log10(频率) Q16
    int32_t  tower_height_q16;// 指数塔高度 H Q16
    TowerLevel level;         // 层级
};

[[nodiscard]] inline Gf3TowerState compute_tower_state(
    uint64_t zhonglv_count
) noexcept {
    Gf3TowerState s{};
    s.zhonglv_count = zhonglv_count;
    s.exp_3 = static_cast<int64_t>(zhonglv_count) * 88;
    s.exp_2 = -static_cast<int64_t>(zhonglv_count) * 128;
    s.freq_log10_q16 = (int32_t)((11319316501LL + s.exp_3 * 2049220185LL
                                        + s.exp_2 * 1292913986LL) >> 16);
    s.tower_height_q16 = tower_height_from_zhonglv_q16(zhonglv_count);
    s.level = classify_level(zhonglv_count);
    return s;
}

// ═══════════════════════════════════════════════════════
// 五、GF(3) 指数塔递推
// ═══════════════════════════════════════════════════════

// GF(3) 域中的指数塔步进: 每次仲吕闭合 = 塔层微步
//   ΔH = 3.4541 / log10(12) ≈ 3.4541 / 1.0792 ≈ 3.201
//   每仲吕闭合增加 ~3.201 塔层单位
inline constexpr int32_t TOWER_STEP_PER_ZHONGLV_Q16 = 209782; // 3.201 × 2¹⁶

// 估算从当前塔高到达目标塔高所需仲吕闭合数
[[nodiscard]] inline uint64_t zhonglv_to_reach_height(
    uint64_t current_zc, int32_t target_height_q16
) noexcept {
    int32_t current_H = tower_height_from_zhonglv_q16(current_zc);
    if (target_height_q16 <= current_H) return 0;
    int64_t delta_H = (int64_t)target_height_q16 - current_H;
    return (uint64_t)((delta_H * 65536) / TOWER_STEP_PER_ZHONGLV_Q16);
}

